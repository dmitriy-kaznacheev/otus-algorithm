#pragma once

#include <vector>

namespace dp {

/**
 * @brief Вычисляет максимальную площадь сарая методом полного перебора
 *
 * @param grid Двумерная матрица: 0 - свободная клетка, 1 - препятствие
 * @return int Максимальная площадь прямоугольника из свободных клеток
 *
 * @note Сложность: O(N² * M²), подходит только для маленьких матриц (N, M ≤ 30)
 */
int max_barn_area_bruteforce(const std::vector<std::vector<int>> &grid);

/**
 * @brief Вычисляет матрицу длин непрерывных свободных клеток "вверх" (на север)
 *
 * @param n Количество строк в матрице
 * @param m Количество столбцов в матрице
 * @param blocked Вектор пар координат (X, Y) препятствий
 * @return std::vector<std::vector<int>> Матрица N×M, где каждый элемент -
 *         количество свободных клеток подряд вверх от данной позиции
 *
 * @note Сложность: O(N * M)
 */
std::vector<std::vector<int>>
compute_barn_length(int n, int m,
                    const std::vector<std::pair<int, int>> &blocked);

/**
 * @brief Для каждого элемента массива длин находит границы максимального
 * отрезка, где все элементы не меньше текущего (вычисляет возможную ширину
 * сарая)
 *
 * @param lengths Входной массив длин (сколько клеток доступно вверх)
 * @return std::pair<std::vector<int>, std::vector<int>> Пара массивов (L, R),
 *         где L[i] - индекс самого левого элемента ≥ lengths[i] (левая граница
 * ширины), R[i] - индекс самого правого элемента ≥ lengths[i] (правая граница
 * ширины)
 *
 * @note Сложность: O(N), использует монотонный стек
 */
std::pair<std::vector<int>, std::vector<int>>
compute_barn_width(const std::vector<int> &lengths);

/**
 * @brief Вычисляет максимальную площадь сарая оптимальным алгоритмом
 *
 * Алгоритм:
 * 1. Для каждой клетки вычисляется длина (сколько свободных клеток вверх)
 * 2. Для каждой строки находится максимальный прямоугольник в гистограмме длин
 * 3. Площадь = длина × ширина прямоугольника
 *
 * @param n Количество строк в матрице
 * @param m Количество столбцов в матрице
 * @param blocked Вектор пар координат (X, Y) препятствий
 * @return int Максимальная площадь прямоугольника из свободных клеток
 *
 * @note Сложность: O(N * M), оптимальное решение для больших матриц (до
 * 1000×1000)
 * @throws std::invalid_argument если координаты препятствий выходят за границы
 */
int max_barn_area(int n, int m,
                  const std::vector<std::pair<int, int>> &blocked);

} // namespace dp
